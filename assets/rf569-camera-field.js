import * as THREE from 'three';
import { Field } from '../field.js?v=55.20';
import { approachYaw } from './rf-camera-v5520.js';
const originalUpdate=Field.prototype.update;
Field.prototype.update=function(dt,input,camera){
 const view=this.o?.cameraView;
 if(!view)return originalUpdate.call(this,dt,input,camera);
 const result=originalUpdate.call(this,dt,input,null);
 if(!camera||!this.player?.pos||dt<=0)return result;
 const p=this.player.pos;
 const inside=this.maze||this.__rf563Story?.mode||/城|天守|神殿|迷宮|洞窟|塔|地下/.test(document.getElementById('field-region')?.textContent||'');
 const boss=this.boss&&!this.boss.dead&&this.boss.pos.distanceTo(p)<24;
 const moving=Math.hypot(input?.mx||0,input?.mz||0)>.15;
 if(moving&&view.yaw===null)this.rfStoryYaw=approachYaw(this.rfStoryYaw??0,input.mx,input.mz,1-Math.exp(-6*dt));
 const yaw=view.yaw??this.rfStoryYaw??0;
 const dist=(inside?8:boss?10:moving?13:11)*(camera.aspect<1?.84:1);
 const target=(this.rfStoryCamera||=new THREE.Vector3()).set(p.x+Math.sin(yaw)*dist,inside?13.3:boss?10.4:11.6,p.z+Math.cos(yaw)*dist);
 if(camera.position.distanceToSquared(target)>1600)camera.position.copy(target);
 else camera.position.lerp(target,1-Math.exp(-5.2*dt));
 camera.lookAt(p.x,1.25,p.z);
 return result;
};
